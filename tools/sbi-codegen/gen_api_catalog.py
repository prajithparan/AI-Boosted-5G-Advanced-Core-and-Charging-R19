#!/usr/bin/env python3
"""Writes libs/sbi-core/src/api_catalog.inc: for every REL-19 API whose YAML declares the
oAuth2ClientCredentials security scheme, the apiName of its `servers` URL ({apiRoot}/<apiName>/<v>),
the service-level OAuth2 scope its `flows.*.scopes` declares (ADR-0499 phase 1) and the NF type
that produces it (phase 3, the targetNfType of a consumer's token request).

The producer NF type comes from the file name's service name, TS<nnnnn>_N<nf>_<Service>.yaml (e.g.
TS29503_Nudm_SDM.yaml -> UDM), upper-cased with '-' as '_', kept only when it is a value of the
NFType enum of TS29510_Nnrf_NFManagement.yaml, or, failing that, when exactly one enum value equals it
with its '_' removed (TS29532_Nmbsmf_TMGI.yaml -> MBSMF -> MB_SMF); otherwise it is reported and
left empty, never guessed.

The service-level scope is the declared scope without a ':' (resource/operation scopes carry one,
TS 29.500 6.7.3). An API declaring none is given its only scope if it declares exactly one; any
other case is reported and left out rather than guessed. An API whose oAuth2ClientCredentials scheme
declares no scope at all (`scopes: {}`, e.g. the TS 29.122/29.522 northbound APIs) gets an empty
scope: a token is still required, but there is no scope to check (ADR-0499).

Usage: gen_api_catalog.py <specs/5G_APIs-REL-19> <output .inc>
"""
import glob
import os
import re
import sys

import yaml


def nf_types(spec_dir: str) -> set[str]:
    with open(os.path.join(spec_dir, "TS29510_Nnrf_NFManagement.yaml"), encoding="utf-8") as f:
        schema = yaml.safe_load(f)["components"]["schemas"]["NFType"]
    return {v for alt in schema.get("anyOf", []) for v in alt.get("enum", [])}


def main(spec_dir: str, out_path: str) -> int:
    table: dict[str, tuple[str, str]] = {}
    skipped = []
    untyped = []
    known_types = nf_types(spec_dir)
    for path in sorted(glob.glob(os.path.join(spec_dir, "TS*.yaml"))):
        try:
            with open(path, encoding="utf-8") as f:
                doc = yaml.safe_load(f)
        except yaml.YAMLError:
            continue
        if not isinstance(doc, dict) or "paths" not in doc:
            continue
        schemes = (doc.get("components") or {}).get("securitySchemes") or {}
        flows = (schemes.get("oAuth2ClientCredentials") or {}).get("flows") or {}
        scopes = sorted({s for fl in flows.values() for s in (fl.get("scopes") or {})})
        if not flows:
            continue
        plain = [s for s in scopes if ":" not in s]
        if not scopes:
            scope = ""  # the scheme declares no scope (e.g. TS 29.122/29.522 northbound APIs)
        elif len(plain) == 1:
            scope = plain[0]
        elif not plain and len(scopes) == 1:
            scope = scopes[0]
        else:
            skipped.append((os.path.basename(path), scopes))
            continue
        m = re.match(r"TS\d+_N([A-Za-z0-9-]+?)_", os.path.basename(path))
        nf_type = m.group(1).upper().replace("-", "_") if m else ""
        if nf_type not in known_types:
            compact = [t for t in known_types if t.replace("_", "") == nf_type.replace("_", "")]
            nf_type = compact[0] if len(compact) == 1 else nf_type
        if nf_type not in known_types:
            untyped.append(os.path.basename(path))
            nf_type = ""
        for server in doc.get("servers") or []:
            m = re.match(r"\{apiRoot\}/([^/]+)/", server.get("url", ""))
            if m is None:
                continue
            name = m.group(1)
            if table.get(name, (scope, nf_type)) != (scope, nf_type):
                skipped.append((os.path.basename(path), [name, table[name], scope, nf_type]))
                continue
            table[name] = (scope, nf_type)
    for f, s in skipped:
        print(f"skipped {f}: {s}", file=sys.stderr)
    for f in untyped:
        print(f"no NFType for {f}", file=sys.stderr)
    with open(out_path, "w", encoding="utf-8") as out:
        out.write("// Generated by tools/sbi-codegen/gen_api_catalog.py from specs/5G_APIs-REL-19 "
                  "-- do not edit.\n")
        out.write("// {apiName, service-level OAuth2 scope, producer NFType or \"\"} (ADR-0499).\n")
        for name, (scope, nf_type) in sorted(table.items()):
            out.write(f'{{"{name}", "{scope}", "{nf_type}"}},\n')
    print(f"{len(table)} APIs, {len(skipped)} skipped, {len(untyped)} files without an NFType")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
